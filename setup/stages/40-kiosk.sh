#!/usr/bin/env bash
# Kid's login session: Cage (a single-app Wayland compositor with no desktop,
# no shortcuts and VT switching off) running Waydroid's full Android UI.
set -euo pipefail

install -m 755 "$TABLET_DIR/files/tablet-kiosk-session" /usr/local/bin/tablet-kiosk-session
install -m 755 "$TABLET_DIR/files/tablet-android" /usr/local/bin/tablet-android
install -m 755 "$TABLET_DIR/files/tablet-splash" /usr/local/bin/tablet-splash
install -m 644 "$TABLET_DIR/files/tablet-kiosk.desktop" /usr/share/wayland-sessions/tablet-kiosk.desktop

# Sound card at full volume and unmuted (saved, so it's restored at boot); the
# kid session puts its own output at 100% too, leaving Android's volume as the
# only control.
# Every card: on many PCs card 0 is the monitor's HDMI and the speakers are on
# another one.
for card in /proc/asound/card[0-9]*; do
  [[ -d $card ]] || continue
  for control in Master PCM "Line Out" Speaker Headphone Front; do
    amixer -q -c "${card##*card}" sset "$control" 100% unmute 2>/dev/null || true
  done
done
alsactl store 2>/dev/null || true

# Touch panels that need a fix are listed in /etc/tablet-os/touch-panels.conf
# (installed once, so a box's own edits are kept). "as-touch": the kernel shows it as a pen that libinput ignores,
# so classify it as a touchscreen. "debounce": start tablet-touch-debounce for it
# (here too, so it follows the panel being unplugged and plugged back in).
panels=/etc/tablet-os/touch-panels.conf
install -d /etc/tablet-os
[[ -e $panels ]] || install -m 644 "$TABLET_DIR/files/touch-panels.conf" "$panels"
{
  echo "# Generated by Kids OS stage 40 from $panels; edit that file, then: sudo ./install.sh 40"
  while read -r line; do
    line="${line%%#*}"
    [[ $line =~ ^[[:space:]]*([0-9a-fA-F]{4}):([0-9a-fA-F]{4})[[:space:]]*(.*)$ ]] || continue
    vendor="${BASH_REMATCH[1],,}" product="${BASH_REMATCH[2],,}" fixes=" ${BASH_REMATCH[3]} "
    match="ACTION==\"add|change\", SUBSYSTEM==\"input\", KERNEL==\"event*\", ATTRS{idVendor}==\"$vendor\", ATTRS{idProduct}==\"$product\""
    [[ $fixes == *" as-touch "* ]] && echo "$match, ENV{ID_INPUT_TABLET}==\"1\", ENV{ID_INPUT_TABLET}=\"\", ENV{ID_INPUT_TABLET_PAD}=\"\", ENV{ID_INPUT_TOUCHSCREEN}=\"1\""
    [[ $fixes == *" debounce "* ]] && echo "${match/add|change/add}, ENV{ID_INPUT_TOUCHSCREEN}==\"1\", TAG+=\"systemd\", ENV{SYSTEMD_WANTS}+=\"tablet-touch-debounce.service\""
  done < "$panels"
} > /etc/udev/rules.d/90-kidsos-touchpanel.rules
udevadm control --reload
udevadm trigger --action=change --subsystem-match=input

# ...and smooth over the momentary lifts some panels report mid-drag (the
# Dell's), which otherwise turn a scroll into taps. Exits quietly without one.
install -m 755 "$TABLET_DIR/files/tablet-touch-debounce" /usr/local/sbin/tablet-touch-debounce
cat > /etc/systemd/system/tablet-touch-debounce.service <<'EOF'
[Unit]
Description=Kids OS touch debounce (drags that blip into taps)
Before=display-manager.service tablet-parent-switch.service

[Service]
ExecStart=/usr/local/sbin/tablet-touch-debounce
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable tablet-touch-debounce.service
systemctl restart tablet-touch-debounce.service
